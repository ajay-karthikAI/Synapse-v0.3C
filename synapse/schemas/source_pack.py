class PackScope(SynapseModel):
    """What the pack is for, and — equally importantly — what it is not for.

    ``excluded_uses`` is mandatory and must be non-empty. A scope that states
    only what a pack is for is not a scope: the boundary is the part that makes
    a review decision possible, because a reviewer must know which questions
    they are *not* approving the pack to answer.
    """

    intended_patient_population: str = Field(
        min_length=1,
        description="Who this pack's sources are appropriate for, e.g. 'adults aged 18+ with an existing type 2 diabetes diagnosis'.",
    )
    intended_use: str = Field(
        min_length=1,
        description="What the pack is approved to support, e.g. 'pre-visit patient education and question preparation'.",
    )
    excluded_uses: list[str] = Field(
        min_length=1,
        description="Uses this pack is explicitly NOT approved for. Must be non-empty.",
    )
    supported_topics: list[str] = Field(
        min_length=1,
        description="Topic boundaries the pack covers. A query outside these is out of scope.",
    )
    out_of_scope_topics: list[str] = Field(
        default_factory=list,
        description="Topics deliberately excluded, recorded so the boundary is explicit rather than merely implied.",
    )


class SourceSelectionPolicy(SynapseModel):
    """The rule by which sources were selected, recorded so it can be audited."""

    description: str = Field(
        min_length=1, description="Human-readable statement of the selection strategy."
    )
    discovery_queries: list[str] = Field(
        default_factory=list,
        description="Search expressions used for automated discovery, verbatim.",
    )
    minimum_evidence_types: list[EvidenceType] = Field(
        min_length=1,
        description="Evidence classes a source must belong to in order to be eligible for approval.",
    )
    maximum_age_years: int | None = Field(
        default=None,
        gt=0,
        description="Sources older than this require explicit reviewer justification. Null means no age limit is applied.",
    )
    required_languages: list[str] = Field(
        default_factory=lambda: ["eng"], description="Language codes accepted into the pack."
    )
    exclude_retracted: bool = Field(
        default=True,
        description="Whether retracted and expression-of-concern sources are excluded. Defaults to true.",
    )
    exclude_preprints: bool = Field(
        default=True,
        description="Whether non-peer-reviewed preprints are excluded. Defaults to true for patient-facing use.",
    )


class ReviewerRequirements(SynapseModel):
    """Who is qualified to approve this pack, and under which rubric."""

    required_role: ReviewerRole = Field(
        default=ReviewerRole.CLINICIAN,
        description="Minimum reviewer role required to approve a source in this pack.",
    )
    minimum_reviewers_per_source: int = Field(
        default=1,
        ge=1,
        description="How many independent reviews each source needs before approval.",
    )
    rubric_version: str = Field(
        min_length=1, description="Version of the review rubric reviewers must apply."
    )
    review_interval_days: int = Field(
        default=365,
        gt=0,
        description="Maximum time between reviews. Drives the review-due date on every approval.",
    )
    separation_of_duties: str = Field(
        default="The reviewer of a source must not be the person who configured its discovery query.",
        description="The separation-of-duties rule in force for this pack, recorded so it can be audited.",
    )


