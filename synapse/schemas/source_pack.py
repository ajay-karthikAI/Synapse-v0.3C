class SourcePackManifest(VersionedModel):
    """The pack's governance record: scope, policy, approval state and integrity."""

    SCHEMA_NAME: ClassVar[str] = "source_pack_manifest"
    SCHEMA_VERSION: ClassVar[str] = (
        "2.0"  # 2.0 replaces the earlier summary-only manifest with a governed one; a MAJOR bump because required fields were added
    )

    # -- identity -----------------------------------------------------------
    pack_id: str = Field(
        description="Stable pack identifier, lowercase kebab-case, e.g. 'diabetes-previsit'."
    )
    version: str = Field(description="Semantic version, MAJOR.MINOR.PATCH.")
    title: str = Field(min_length=1, description="Human-readable pack name.")
    description: str = Field(min_length=1, description="What this pack contains and why it exists.")

    # -- scope and policy ---------------------------------------------------
    scope: PackScope = Field(
        description="Intended population, intended use, excluded uses and topic boundaries."
    )
    selection_policy: SourceSelectionPolicy = Field(
        description="How sources were selected, and the minimum evidence requirements."
    )
    reviewer_requirements: ReviewerRequirements = Field(
        description="Who may approve, under which rubric, and how often review recurs."
    )

    # -- approval -----------------------------------------------------------
    approval_state: PackApprovalState = Field(
        default=PackApprovalState.DRAFT,
        description="Governance state of the whole pack. Defaults to draft.",
    )
    approved_at: datetime | None = Field(
        default=None,
        description="When the pack was approved. Required for 'approved', forbidden otherwise.",
    )
    approved_by: str | None = Field(
        default=None,
        description="Pseudonymous identifier of the approving reviewer. Never generated by this software.",
    )
    review_due_at: date | None = Field(
        default=None,
        description="When the pack approval must be revisited. Required for 'approved'.",
    )
    superseded_by_version: str | None = Field(
        default=None, description="Version that replaces this one, when superseded."
    )

    # -- integrity ----------------------------------------------------------
    corpus_sha256: str = Field(
        description="Order-sensitive digest over the serialised sources. Any content change alters it, which is what forces a version bump."
    )
    source_count: int = Field(ge=0, description="Number of sources in the pack.")
    lifecycle_counts: dict[str, int] = Field(
        default_factory=dict,
        description="Source counts per lifecycle state. Always carries every state, so a reader can see at a glance that nothing is approved.",
    )

    # -- provenance ---------------------------------------------------------
    build_tool_version: str = Field(
        min_length=1, description="Version of the tool that produced this manifest."
    )
    created_at: datetime = Field(description="When the pack was first created (timezone-aware).")
    updated_at: datetime = Field(description="When the manifest was last written (timezone-aware).")
    notes: str = Field(
        default="", description="Operational notes. Must not contain clinical assertions."
    )

    @field_validator("pack_id")
    @classmethod
    def _validate_pack_id(cls, value: str) -> str:
        """Pack identifiers double as directory names, so the grammar is strict."""
        if not PACK_ID_PATTERN.match(value):
            raise ValueError("pack_id must be lowercase kebab-case, e.g. 'diabetes-previsit'")
        return value

    @field_validator("version", "superseded_by_version")
    @classmethod
    def _validate_semver(cls, value: str | None) -> str | None:
        """Strict MAJOR.MINOR.PATCH, so versions order unambiguously."""
        if value is not None and not SEMVER_PATTERN.match(value):
            raise ValueError("version must be a semantic version, MAJOR.MINOR.PATCH")
        return value

    @field_validator("corpus_sha256")
    @classmethod
    def _validate_digest_shape(cls, value: str) -> str:
        """Reject anything that is not a lowercase 64-character hex digest."""
        if not is_sha256_hex(value):
            raise ValueError("corpus_sha256 must be 64 lowercase hexadecimal characters")
        return value

    @field_validator("approved_by")
    @classmethod
    def _validate_approver(cls, value: str | None) -> str | None:
        """The approver must be a pseudonymous identifier supplied by an operator."""
        if value is not None and not is_valid_reviewer_id(value):
            raise ValueError(
                "approved_by must match 'rev_' followed by 8 lowercase alphanumeric characters"
            )
        return value

    @model_validator(mode="after")
    def _validate_approval_invariants(self) -> SourcePackManifest:
        """Enforce that an approval claim carries all of its required evidence.

        This is requirement 5's first rule in its strongest form: the
        ``approved`` state is simply not constructible without the fields that
        make it meaningful and revocable.
        """
        if self.approval_state is PackApprovalState.APPROVED:
            missing = [
                name
                for name, value in (
                    ("approved_at", self.approved_at),
                    ("approved_by", self.approved_by),
                    ("review_due_at", self.review_due_at),
                )
                if value is None
            ]
            if missing:  # Reported together so an operator fixes them in one pass
                raise ValueError(f"approval_state 'approved' requires: {', '.join(missing)}")
            if self.source_count == 0:  # An approved pack with no sources approves nothing
                raise ValueError("approval_state 'approved' requires at least one source")
        else:
            # The converse matters just as much: approval metadata lingering on
            # a draft would make a later reader believe a decision exists.
            for name, value in (
                ("approved_at", self.approved_at),
                ("approved_by", self.approved_by),
            ):
                if value is not None:
                    raise ValueError(f"{name} must be null unless approval_state is 'approved'")

        if self.approval_state is PackApprovalState.SUPERSEDED and not self.superseded_by_version:
            raise ValueError("approval_state 'superseded' requires superseded_by_version")

        require_timezone_aware(self.created_at, "created_at")
        require_timezone_aware(self.updated_at, "updated_at")
        if self.approved_at is not None:
            require_timezone_aware(self.approved_at, "approved_at")
        if self.updated_at < self.created_at:  # Usually a timezone bug rather than time travel
            raise ValueError("updated_at must not precede created_at")
        if self.lifecycle_counts and sum(self.lifecycle_counts.values()) != self.source_count:
            raise ValueError("lifecycle_counts must sum to source_count")
        return self

    @property
    def is_example(
        self,
    ) -> bool:  # Used by the eligibility layer to refuse demonstration content outright
        """True when this pack is demonstration content."""
        return self.approval_state is PackApprovalState.UNAPPROVED_EXAMPLE


