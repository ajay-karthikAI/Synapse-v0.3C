"""
synapse.schemas.source_pack
===========================
The source pack: a versioned, reviewable collection of medical sources scoped
to one narrowly defined product use.

The distinction this module exists to enforce, stated once:

    **Automated discovery is not clinical approval.**

An ingestion run can establish that a publication exists, is in a topic area,
and carries certain publisher metadata. It cannot establish that the
publication is appropriate for a particular patient population, in a particular
product, for a particular purpose. Only a qualified human reviewer can, and
only by recording *why*.

The schema makes the second thing unconstructible without the first's evidence:
a :class:`PackSource` cannot hold ``lifecycle_state = "approved"`` unless it
also carries a complete :class:`ClinicianReview`, and a
:class:`SourcePackManifest` cannot hold ``approval_state = "approved"`` unless
its scope, reviewer requirements and approval timestamps are all present. There
is no code path that produces an approval as a side effect of anything.

Records are self-contained by design. A reviewer reads ``sources.jsonl`` and
must be able to judge each entry without joining against a corpus artifact, so
bibliographic fields are duplicated into the pack rather than referenced.
"""

from __future__ import annotations  # Postponed annotations

import re  # Semantic-version validation
from datetime import date, datetime
from typing import ClassVar

from pydantic import Field, field_validator, model_validator

from synapse.hashing import is_sha256_hex
from synapse.identifiers import is_valid_document_id, is_valid_reviewer_id
from synapse.schemas.base import SynapseModel, VersionedModel, require_timezone_aware
from synapse.schemas.enums import (
    EvidenceType,
    PackApprovalState,
    RetractionStatus,
    ReviewDecision,
    ReviewerRole,
    SourceLifecycleState,
)
from synapse.schemas.source import Author, SourceContainer

SEMVER_PATTERN = re.compile(
    r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$"
)  # Strict MAJOR.MINOR.PATCH; no pre-release or build suffixes, so version ordering is unambiguous

PACK_ID_PATTERN = re.compile(
    r"^[a-z][a-z0-9]*(-[a-z0-9]+)*$"
)  # Lowercase kebab-case, e.g. 'diabetes-previsit'. Also used as a directory name, so no separators or spaces.

# States that cannot exist without a review record. Named here rather than
# inlined so the rule reads as one thing and is greppable from both
# enforcement points (this model, and synapse.governance.states).
REVIEW_REQUIRED_LIFECYCLE_STATES = frozenset(
    {SourceLifecycleState.SCREENED, SourceLifecycleState.APPROVED, SourceLifecycleState.REJECTED}
)

_ALLOWED_URL_SCHEMES = (
    "http://",
    "https://",
)  # A canonical URL is rendered as a clickable citation; other schemes are a link-injection surface


