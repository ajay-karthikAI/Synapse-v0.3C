class PackSource(VersionedModel):
    """One source inside a pack: its citation, and its governance standing."""

    SCHEMA_NAME: ClassVar[str] = "pack_source"
    SCHEMA_VERSION: ClassVar[str] = "1.0"

    # -- identity -----------------------------------------------------------
    document_id: str = Field(description="Stable document identifier, '<scheme>:<key>'.")
    canonical_url: str = Field(
        min_length=1,
        description="Exact canonical URL of the source. Not a template, not a search link.",
    )
    pmid: str | None = Field(
        default=None, description="PubMed identifier, when the source has one."
    )
    doi: str | None = Field(
        default=None, description="DOI, normalised to lowercase without a resolver prefix."
    )
    guideline_id: str | None = Field(
        default=None, description="Issuing organisation's guideline identifier, when applicable."
    )

    # -- citation -----------------------------------------------------------
    title: str = Field(
        min_length=1, description="Full title, including any text inside nested markup."
    )
    authors: list[Author] = Field(
        default_factory=list,
        description="Authors as published. Empty when unavailable — never inferred.",
    )
    container: SourceContainer = Field(
        default_factory=SourceContainer,
        description="Journal, or the organisation issuing a guideline.",
    )
    publication_date: date | None = Field(
        default=None, description="Original publication date, when known."
    )
    revision_date: date | None = Field(
        default=None, description="Latest revision date, for guidelines that are revised in place."
    )
    evidence_type: EvidenceType = Field(
        default=EvidenceType.UNCLASSIFIED, description="Normalised evidence class."
    )
    language: str | None = Field(
        default=None, description="Primary language code as published, e.g. 'eng'."
    )

    # -- governance ---------------------------------------------------------
    lifecycle_state: SourceLifecycleState = Field(
        default=SourceLifecycleState.DISCOVERED,
        description="Governance standing. Automation may only ever produce 'discovered'.",
    )
    review: ClinicianReview | None = Field(
        default=None,
        description="Human review record. Required for screened/approved/rejected; forbidden for discovered.",
    )
    exclusion_reason: str | None = Field(
        default=None,
        description="Why this source is excluded. Required for rejected, expired and superseded.",
    )
    superseded_by: str | None = Field(
        default=None, description="Document identifier of the source that replaces this one."
    )
    retraction_status: RetractionStatus = Field(
        default=RetractionStatus.UNCHECKED,
        description="Retraction screening state carried through from ingestion.",
    )

    # -- provenance ---------------------------------------------------------
    content_sha256: str = Field(
        description="SHA-256 of the source's normalised text at the time it entered the pack. Detects the source changing under a completed review."
    )
    discovered_at: datetime = Field(
        description="When automated discovery added this entry (timezone-aware)."
    )
    discovery_method: str = Field(
        min_length=1,
        description="How this source was found, e.g. 'pubmed_esearch' or 'manual_entry'. An approval is only as good as the provenance of what was reviewed.",
    )

    @field_validator("document_id")
    @classmethod
    def _validate_document_id(cls, value: str) -> str:
        """Reject identifiers outside the grammar."""
        if not is_valid_document_id(value):
            raise ValueError("document_id does not match the required '<scheme>:<key>' grammar")
        return value

    @field_validator("canonical_url")
    @classmethod
    def _validate_url_scheme(cls, value: str) -> str:
        """Restrict URLs to http/https, as they are rendered as clickable citations."""
        if not value.startswith(_ALLOWED_URL_SCHEMES):
            raise ValueError("canonical_url must be an http:// or https:// URL")
        return value

    @field_validator("content_sha256")
    @classmethod
    def _validate_digest_shape(cls, value: str) -> str:
        """Reject anything that is not a lowercase 64-character hex digest."""
        if not is_sha256_hex(value):
            raise ValueError("content_sha256 must be 64 lowercase hexadecimal characters")
        return value

    @field_validator("superseded_by")
    @classmethod
    def _validate_superseded_by(cls, value: str | None) -> str | None:
        """A supersession must point at a well-formed identifier."""
        if value is not None and not is_valid_document_id(value):
            raise ValueError("superseded_by must be a well-formed document identifier")
        return value

    @model_validator(mode="after")
    def _validate_lifecycle_invariants(self) -> PackSource:
        """Enforce the automation/approval separation at the record level.

        These are the rules that make "approved" impossible to assert without
        the evidence that licenses it.
        """
        state = self.lifecycle_state

        if state is SourceLifecycleState.DISCOVERED and self.review is not None:
            # A discovered entry carrying a review is contradictory: either it
            # was reviewed (and belongs in a later state) or the record is
            # malformed. Silently allowing it would let a review be attached
            # without advancing the state a reader checks.
            raise ValueError("a 'discovered' source must not carry a review record")

        # The core rule: these three states are human judgements, so each
        # requires the record proving a judgement actually happened.
        if state in REVIEW_REQUIRED_LIFECYCLE_STATES and self.review is None:
            raise ValueError(f"lifecycle_state '{state.value}' requires a review record")

        if state is SourceLifecycleState.APPROVED:
            if (
                self.review is None or self.review.decision is not ReviewDecision.APPROVED
            ):  # A 'needs changes' review cannot license approval
                raise ValueError(
                    "lifecycle_state 'approved' requires a review whose decision is 'approved'"
                )
            if (
                self.review.reviewer_role is not ReviewerRole.CLINICIAN
            ):  # Non-clinical review cannot approve clinical content
                raise ValueError("lifecycle_state 'approved' requires a clinician reviewer")

        if state is SourceLifecycleState.REJECTED:
            if (
                self.review is not None and self.review.decision is ReviewDecision.APPROVED
            ):  # Contradictory: an approving review under a rejected state
                raise ValueError("lifecycle_state 'rejected' must not carry an approving review")
            if (
                not self.exclusion_reason
            ):  # A rejection with no reason cannot be revisited or audited
                raise ValueError("lifecycle_state 'rejected' requires an exclusion_reason")

        if (
            state in (SourceLifecycleState.EXPIRED, SourceLifecycleState.SUPERSEDED)
            and not self.exclusion_reason
        ):
            raise ValueError(f"lifecycle_state '{state.value}' requires an exclusion_reason")

        if (
            state is SourceLifecycleState.SUPERSEDED and not self.superseded_by
        ):  # A supersession that names no successor is untraceable
            raise ValueError("lifecycle_state 'superseded' requires superseded_by")

        require_timezone_aware(self.discovered_at, "discovered_at")
        return self

    @property
    def is_approved(self) -> bool:  # Convenience predicate used by the eligibility layer
        """True only when this source carries a complete clinician approval."""
        return self.lifecycle_state is SourceLifecycleState.APPROVED

    def review_expired_on(self, as_of: date) -> bool:
        """True when an approval's review-due date has passed as of ``as_of``."""
        if self.review is None:  # Nothing to expire
            return False
        return self.review.review_due_at < as_of


