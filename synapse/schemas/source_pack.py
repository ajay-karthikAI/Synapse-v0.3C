class ClinicianReview(SynapseModel):
    """A recorded human review of one source, against one pack's declared scope.

    The six assessment fields are mandatory and free-text-with-a-floor: a
    reviewer must actually write something in each. A review that records only
    a decision is not a review — it is an assertion, and it gives a later
    auditor no way to tell whether the scope was actually considered.
    """

    reviewer_id: str = Field(
        description="Pseudonymous reviewer identifier, 'rev_' + 8 lowercase alphanumerics. Supplied by the operator; NEVER generated by this software."
    )
    reviewer_role: ReviewerRole = Field(
        description="Reviewer's role. Only 'clinician' may approve clinical content for patient-facing use."
    )
    reviewed_at: datetime = Field(description="When the review was recorded (timezone-aware).")
    review_due_at: date = Field(
        description="Date this decision must be revisited. An approval without an expiry silently becomes permanent."
    )
    rubric_version: str = Field(
        min_length=1,
        description="Version of the review rubric applied, so a decision can be interpreted against the standard in force at the time.",
    )

    # -- the six assessment dimensions (requirement 7) ----------------------
    relevance: str = Field(
        min_length=1, description="Is this source relevant to the pack's supported topics?"
    )
    population_applicability: str = Field(
        min_length=1,
        description="Does the study population match the pack's intended patient population?",
    )
    evidence_quality: str = Field(
        min_length=1, description="Assessment of study design, conduct and strength of evidence."
    )
    known_limitations: str = Field(
        min_length=1, description="Limitations a patient-facing answer must not overstate past."
    )
    patient_safety_concerns: str = Field(
        min_length=1,
        description="Safety concerns arising from patient-facing use. 'None identified' is a valid answer; silence is not.",
    )

    decision: ReviewDecision = Field(description="The reviewer's decision.")
    decision_rationale: str = Field(
        min_length=1, description="Why this decision, in the reviewer's own words."
    )

    @field_validator("reviewer_id")
    @classmethod
    def _validate_reviewer_pseudonymity(cls, value: str) -> str:
        """Enforce pseudonymity at the schema boundary.

        The mapping from pseudonym to person is held outside this repository, so
        a clone of a source pack never carries reviewer identities.
        """
        if not is_valid_reviewer_id(value):
            raise ValueError(
                "reviewer_id must match 'rev_' followed by 8 lowercase alphanumeric characters"
            )
        return value

    @field_validator(
        "relevance",
        "population_applicability",
        "evidence_quality",
        "known_limitations",
        "patient_safety_concerns",
        "decision_rationale",
    )
    @classmethod
    def _validate_substantive_text(cls, value: str) -> str:
        """Reject whitespace-only and placeholder answers.

        Without this, a template filled in with "-" or "n/a" would satisfy
        ``min_length=1`` and produce a review that documents nothing.
        """
        stripped = value.strip()
        if not stripped:
            raise ValueError("review fields must not be blank")
        if stripped.lower() in {
            "n/a",
            "na",
            "-",
            "--",
            "tbd",
            "todo",
            "?",
        }:  # Common placeholder tokens; an explicit "None identified" is accepted
            raise ValueError("review fields must contain a substantive answer, not a placeholder")
        return value

    @model_validator(mode="after")
    def _validate_review(self) -> ClinicianReview:
        """Reject naive timestamps and reviews whose expiry precedes the review."""
        require_timezone_aware(self.reviewed_at, "reviewed_at")
        if (
            self.review_due_at < self.reviewed_at.date()
        ):  # An already-expired approval is meaningless
            raise ValueError("review_due_at must not precede reviewed_at")
        return self


