def _free_port() -> int:
    """An unused localhost port."""
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        return probe.getsockname()[1]


@pytest.fixture(scope="module")
def streamlit_server():
    """Run the real app on localhost, or skip.

    Only the empty state is exercised, so no API key, corpus or index is needed
    and no network call is made.
    """
    port = _free_port()
    streamlit_binary = shutil.which("streamlit")
    if streamlit_binary is None:
        pytest.skip("streamlit is not on PATH")
    # Fixed argument list, absolute binary, no shell: nothing here is
    # attacker-influenced, and resolving the path satisfies the linter's
    # partial-executable rule rather than suppressing it.
    process = subprocess.Popen(  # noqa: S603
        [
            streamlit_binary,
            "run",
            "app.py",
            "--server.port",
            str(port),
            "--server.headless",
            "true",
            "--browser.gatherUsageStats",
            "false",
        ],
        cwd=REPO_ROOT,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env={**__import__("os").environ, "SYNAPSE_TELEMETRY": "0"},
    )
    url = f"http://127.0.0.1:{port}"
    for _ in range(60):
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=0.5):
                break
        except OSError:
            time.sleep(0.5)
    else:
        process.terminate()
        pytest.skip("streamlit did not start")
    time.sleep(2)  # Let the first script run finish
    yield url
    # Streamlit does not always exit on SIGTERM within a sensible window, and a
    # teardown that raises turns a passing suite red.
    process.terminate()
    try:
        process.wait(timeout=10)
    except subprocess.TimeoutExpired:
        process.kill()
        process.wait(timeout=10)


@pytest.mark.slow
class TestLiveApplication:
    """The real Streamlit page, empty state only."""

    def test_the_question_field_has_a_visible_label(self, browser, streamlit_server) -> None:
        page = browser.new_page()
        try:
            page.goto(streamlit_server, wait_until="networkidle")
            page.wait_for_selector("textarea", timeout=15000)
            label = page.get_by_text("Your question or symptoms").first
            assert label.is_visible(), "the question field has no visible label"
        finally:
            page.close()

    def test_the_skip_link_is_reachable_early_and_visible_on_focus(
        self, browser, streamlit_server
    ) -> None:
        """The skip link cannot be literally first, and that is a Streamlit limit.

        Streamlit renders its own header, toolbar and sidebar before any
        application content, with no supported way to insert markup ahead of
        them. So the requirement is that the link is reachable within a short
        run of tab stops and becomes visible when focused, not that it is stop
        number one.

        Reachability is asserted on element identity rather than on the text of
        ``document.activeElement``: Streamlit wraps markdown in containers whose
        textContent includes the link, so a text match reports success while
        focus is still on a wrapper.
        """
        page = browser.new_page()
        try:
            page.goto(streamlit_server, wait_until="networkidle")
            page.wait_for_selector("textarea", timeout=15000)

            found_at = None
            for index in range(1, 16):
                page.keyboard.press("Tab")
                if page.evaluate(
                    "() => document.activeElement === document.querySelector('a.skip-link')"
                ):
                    found_at = index
                    break
            assert found_at is not None, "the skip link was not reachable in the first 15 tab stops"

            # Focused, it must come on-screen; unfocused it stays out of the way.
            offset = page.evaluate(
                "() => { const a = document.querySelector('a.skip-link');"
                " a.focus(); return a.getBoundingClientRect().x; }"
            )
            assert offset >= -1, f"the skip link stays off-screen when focused (x={offset})"
        finally:
            page.close()

    def test_a_collapsed_sidebar_is_not_in_the_tab_order(self, browser, streamlit_server) -> None:
        """Focus must not land on controls the user cannot see.

        A collapsed Streamlit sidebar is moved off-screen with a transform but
        keeps visibility:visible, so its API key field, its checkbox and its
        buttons stayed focusable at x=-305. Eight invisible stops on a phone,
        before anything perceivable. The fix is a visibility rule keyed on
        aria-expanded, which Streamlit already sets.
        """
        page = browser.new_page(viewport={"width": 390, "height": 800})
        try:
            page.goto(streamlit_server, wait_until="networkidle")
            page.wait_for_selector("textarea", timeout=15000)
            focusable_in_sidebar = page.evaluate(
                "() => { const s = document.querySelector('[data-testid=\"stSidebar\"]');"
                " if (!s) return 0;"
                " if (getComputedStyle(s).visibility === 'hidden') return 0;"
                " return s.querySelectorAll('input, textarea, select, button, a[href]').length; }"
            )
            assert focusable_in_sidebar == 0, (
                f"{focusable_in_sidebar} controls in the collapsed sidebar are still focusable"
            )
        finally:
            page.close()

    def test_no_axe_violations_on_the_empty_state(self, browser, streamlit_server) -> None:
        page = browser.new_page()
        try:
            page.goto(streamlit_server, wait_until="networkidle")
            page.wait_for_selector("textarea", timeout=15000)
            ours, framework = partition_violations(run_axe(page))
            # Framework findings are reported, not asserted: they sit in
            # Streamlit's own DOM, cannot be fixed from app.py, and are listed
            # with a remediation route in docs/accessibility.md §8. Failing the
            # build on them would mean patching a vendor's markup or switching
            # the check off entirely, and the second always wins eventually.
            if framework:
                print("\nStreamlit framework findings (not fixable from app.py):")
                print(describe(framework))
            assert ours == [], describe(ours)
        finally:
            page.close()
